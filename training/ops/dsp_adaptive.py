"""ws-defend-sparse: Adaptive curriculum ladder controller.

On a gate fail, instead of stopping: interpolate stage params toward the previous stage
(difficulty alpha in [0,1]), warm-start retrain at lower alpha until it passes, then step
alpha back up to 1.0 before advancing to the next stage.

Interpolated params (S_prev -> S_cur):
  - capture_radius
  - attacker_difficulty
  - attacker_speed (both bounds)
  - rew_scale_crash  (bumped per fail to penalise crashing more)

Usage (from simulation_infra/):
    python ../ops/dsp_adaptive.py [options]

Options:
    --start_stage INT   (default 3)
    --end_stage   INT   (default 6)
    --ckpt        PATH  warm-start checkpoint for start_stage
    --iters       INT   per-alpha training budget  (default 400)
    --eval_ep     INT   (default 256)
    --num_envs    INT   (default 2048)
    --seed        INT   (default 42)
    --max_retries INT   max alpha-down steps per stage before giving up (default 4)
    --alpha_step  FLOAT step size when raising alpha back to 1.0 (default 0.33)
    --crash_bump  FLOAT additive rew_scale_crash bump per fail (default 5.0)
    --dynamics    STR   cascade|velocity|auto
    --tsv         PATH  log file  (default outputs/dsp_adaptive_log.tsv)
    --job_id      STR   SLURM job id tag
"""
import argparse
import json
import os
import shlex
import subprocess
import sys
import time
from pathlib import Path

# ── stage interpolation params (only the ones we ease) ───────────────────────
STAGE_PARAMS = {
    2: dict(capture_radius=0.40, attacker_difficulty=0.2,
            attacker_speed=[0.4, 0.9], active_attackers_max=2),
    3: dict(capture_radius=0.25, attacker_difficulty=0.3,
            attacker_speed=[0.4, 0.9], active_attackers_max=2),
    4: dict(capture_radius=0.25, attacker_difficulty=0.4,
            attacker_speed=[0.4, 0.9], active_attackers_max=3),
    5: dict(capture_radius=0.25, attacker_difficulty=0.6,
            attacker_speed=[0.8, 1.2], active_attackers_max=3),
    6: dict(capture_radius=0.25, attacker_difficulty=0.9,
            attacker_speed=[0.8, 1.2], active_attackers_max=4),
}

def _lerp(a, b, t):
    return a + t * (b - a)

def interpolated_params(stage: int, alpha: float, crash_scale: float) -> dict:
    """Return cfg overrides for (stage, alpha). alpha=1 -> full S{stage}, alpha=0 -> S{stage-1}."""
    prev = stage - 1
    if prev not in STAGE_PARAMS or stage not in STAGE_PARAMS:
        return {"rew_scale_crash": crash_scale}
    p0, p1 = STAGE_PARAMS[prev], STAGE_PARAMS[stage]
    return {
        "capture_radius":      round(_lerp(p0["capture_radius"],      p1["capture_radius"],      alpha), 4),
        "attacker_difficulty": round(_lerp(p0["attacker_difficulty"],  p1["attacker_difficulty"], alpha), 4),
        "attacker_speed_lo":   round(_lerp(p0["attacker_speed"][0],    p1["attacker_speed"][0],   alpha), 4),
        "attacker_speed_hi":   round(_lerp(p0["attacker_speed"][1],    p1["attacker_speed"][1],   alpha), 4),
        "rew_scale_crash":     round(crash_scale, 2),
    }

def _write_adap_tasks(stage: int, params: dict, ops_dir: str) -> str:
    """Write ops/dsp_adap_tasks.py with a single @configclass baking in (stage, params).
    Called before each training run; the subprocess imports it. Returns the class name."""
    cls = f"AdaptiveS{stage}"
    lo  = params.get("attacker_speed_lo", STAGE_PARAMS.get(stage, {}).get("attacker_speed", [0.4, 0.9])[0])
    hi  = params.get("attacker_speed_hi", STAGE_PARAMS.get(stage, {}).get("attacker_speed", [0.4, 0.9])[1])
    lines = [
        '"""Auto-generated by dsp_adaptive.py — do not hand-edit."""',
        "from isaaclab.utils import configclass",
        "from action_space_kit.tasks.direct.tello_defend.tello_defend_env_cfg import (",
        "    TelloDefendLiveEnvCfg, apply_curriculum",
        ")",
        "",
        "@configclass",
        f"class {cls}(TelloDefendLiveEnvCfg):",
        f"    curriculum_stage: int = {stage}",
        "    def __post_init__(self):",
        f"        apply_curriculum(self, {stage})",
        f"        self.capture_radius      = {params['capture_radius']}",
        f"        self.attacker_difficulty = {params['attacker_difficulty']}",
        f"        self.attacker_speed      = [{lo}, {hi}]",
        f"        self.rew_scale_crash     = {params['rew_scale_crash']}",
    ]
    dst = os.path.join(ops_dir, "dsp_adap_tasks.py")
    with open(dst, "w") as f:
        f.write("\n".join(lines) + "\n")
    return cls

def _adatrain_script(ops_dir: str) -> str:
    """Write ops/dsp_adatrain.py if not present — mirrors dsp_train.py but for Adaptive tasks."""
    dst = os.path.join(ops_dir, "dsp_adatrain.py")
    if os.path.exists(dst):
        return dst
    src = os.path.join(ops_dir, "dsp_train.py")
    with open(src) as f:
        text = f.read()
    # Replace the task registration block to also register Adaptive tasks
    insert = (
        "\nfor _k in range(3, 8):\n"
        "    gym.register(\n"
        "        id=f'AS-Defend-Adaptive-S{_k}-v0',\n"
        "        entry_point=f'{PKG}.tello_defend_env:TelloDefendEnv',\n"
        "        disable_env_checker=True,\n"
        "        kwargs={\n"
        "            'env_cfg_entry_point': f'dsp_adap_tasks:AdaptiveS{_k}',\n"
        "            'skrl_cfg_entry_point': f'{PKG}.agents:skrl_ppo_cfg.yaml',\n"
        "            'skrl_ippo_cfg_entry_point': f'{PKG}.agents:skrl_ippo_cfg.yaml',\n"
        "            'skrl_mappo_cfg_entry_point': f'{PKG}.agents:skrl_mappo_cfg.yaml',\n"
        "        },\n"
        "    )\n"
    )
    # insert after last gym.register block
    text = text.replace(
        'sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # for dsp_tasks',
        'sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # for dsp_tasks / dsp_adap_tasks'
        + insert
    )
    with open(dst, "w") as f:
        f.write(text)
    return dst

# ── eval helpers ──────────────────────────────────────────────────────────────

def _read_last_result(out_json: str, before: int) -> dict:
    if not os.path.exists(out_json):
        return {}
    with open(out_json) as f:
        lines = f.readlines()
    new = lines[before:]
    if not new:
        return {}
    try:
        rec = json.loads(new[-1])
        return dict(downed=rec.get("downed_per_episode", 0.0),
                    breach=rec.get("breach_rate", 1.0),
                    crashes=rec.get("stats", {}).get("Episode/crashes", 0.0))
    except Exception:
        return {}

def _line_count(path: str) -> int:
    if not os.path.exists(path):
        return 0
    with open(path) as f:
        return sum(1 for _ in f)

def _eval_run(sim_dir: str, stage: int, ckpt: str | None, baseline: str | None,
              eval_ep: int, job_id: str) -> dict:
    out_json = os.path.join(sim_dir, "outputs", "evaluate_results.jsonl")
    before = _line_count(out_json)
    cmd = [sys.executable, "-u",
           os.path.join(sim_dir, "scripts", "evaluate.py"),
           "--task", f"AS-Defend-Live-S{stage}-v0",
           "--num_envs", str(min(eval_ep, 256)),
           "--episodes", str(eval_ep),
           "--seed", "7",
           "--set", f"curriculum_stage={stage}", "reward_mode='sparse'"]
    if baseline:
        cmd += ["--baseline", baseline]
    if ckpt:
        cmd += ["--algorithm", "MAPPO", "--checkpoint", ckpt]
    print(f"[adaptive] EVAL S{stage} {'baseline='+baseline if baseline else 'ckpt='+str(ckpt)}")
    subprocess.run(cmd, cwd=sim_dir)
    return _read_last_result(out_json, before)

def _latest_run(log_root: str, name: str) -> str | None:
    dirs = sorted(Path(log_root).glob(f"*_{name}"), key=lambda p: p.stat().st_mtime, reverse=True)
    return str(dirs[0]) if dirs else None

def _best_ckpt(run_dir: str | None) -> str | None:
    if not run_dir:
        return None
    p = Path(run_dir) / "checkpoints" / "best_agent.pt"
    if p.exists():
        return str(p)
    ckpts = sorted((Path(run_dir) / "checkpoints").glob("agent_*.pt"),
                   key=lambda x: int(x.stem.split("_")[-1]))
    return str(ckpts[-1]) if ckpts else None

def _tsv_append(tsv_path: str, row: dict):
    is_new = not os.path.exists(tsv_path)
    with open(tsv_path, "a") as f:
        if is_new:
            f.write("\t".join(str(k) for k in row.keys()) + "\n")
        f.write("\t".join(str(v) for v in row.values()) + "\n")
    print(f"[tsv] {row}")

# ── main ──────────────────────────────────────────────────────────────────────

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--start_stage", type=int,   default=3)
    p.add_argument("--end_stage",   type=int,   default=6)
    p.add_argument("--ckpt",        type=str,   default="")
    p.add_argument("--iters",        type=int,   default=600)
    p.add_argument("--eval_ep",      type=int,   default=256)
    p.add_argument("--num_envs",     type=int,   default=16384)
    p.add_argument("--mini_batches", type=int,   default=16)
    p.add_argument("--seed",         type=int,   default=42)
    p.add_argument("--max_retries",  type=int,   default=4)
    p.add_argument("--alpha_step",   type=float, default=0.33)
    p.add_argument("--crash_bump",   type=float, default=5.0)
    p.add_argument("--dynamics",    type=str,   default="auto")
    p.add_argument("--tsv",         type=str,   default="outputs/dsp_adaptive_log.tsv")
    p.add_argument("--job_id",      type=str,   default=os.environ.get("SLURM_JOB_ID", "local"))
    args = p.parse_args()

    repo    = os.environ.get("REPO", str(Path(__file__).resolve().parents[1]))
    ops_dir = os.path.join(repo, "ops")
    sim_dir = os.path.join(repo, "simulation_infra")
    log_root= os.path.join(sim_dir, "logs", "skrl", "tello_defend")
    os.makedirs(os.path.join(sim_dir, "outputs"), exist_ok=True)
    tsv = os.path.join(sim_dir, args.tsv)

    adatrain = _adatrain_script(ops_dir)
    ckpt     = args.ckpt or ""
    BASE_CRASH = -10.0

    for stage in range(args.start_stage, args.end_stage + 1):
        print(f"\n{'='*60}\n[adaptive] === STAGE {stage} ===\n{'='*60}")
        dyn = args.dynamics if args.dynamics != "auto" else ("velocity" if stage <= 3 else "cascade")

        # scripted baseline
        base = _eval_run(sim_dir, stage, None, "assign-lead-safe", args.eval_ep, args.job_id)
        base_d  = base.get("downed",  7.0)
        base_br = base.get("breach",  0.0)
        base_cr = base.get("crashes", 0.0)
        print(f"[adaptive] baseline S{stage}: downed={base_d:.3f} breach={base_br:.3f} crashes={base_cr:.3f}")
        _tsv_append(tsv, dict(stage=stage, alpha="baseline", downed=round(base_d,4),
                               breach=round(base_br,4), crashes=round(base_cr,4),
                               pass_=1, crash_scale=BASE_CRASH, job=args.job_id, ts=int(time.time())))

        crash_scale = BASE_CRASH
        alpha       = 1.0
        retry       = 0
        stage_ckpt  = ckpt
        stage_pass  = False

        while retry <= args.max_retries:
            params  = interpolated_params(stage, alpha, crash_scale)
            cls_name= _write_adap_tasks(stage, params, ops_dir)
            task_id = f"AS-Defend-Adaptive-S{stage}-v0"
            name    = f"adaptive_s{stage}_a{int(alpha*100):03d}_t{retry}"

            log_path = os.path.join(sim_dir, "outputs",
                                    f"dsp_adap_{stage}_{int(alpha*100):03d}_{retry}_{args.job_id}.log")

            cmd = [sys.executable, "-u", adatrain,
                   "--task", task_id, "--algorithm", "MAPPO",
                   "--headless", "--num_envs", str(args.num_envs),
                   "--seed", str(args.seed + retry),
                   "--max_iterations", str(args.iters),
                   f"env.dynamics_model={dyn}",
                   "env.reward_mode=sparse",
                   "agent.models.policy.clip_actions=False",
                   "agent.agent.learning_rate_scheduler=null",
                   "agent.agent.learning_rate=3e-4",
                   "agent.agent.discount_factor=0.99",
                   "agent.agent.time_limit_bootstrap=True",
                   f"agent.agent.mini_batches={args.mini_batches}",
                   f"agent.agent.experiment.experiment_name={name}"]
            if stage_ckpt:
                cmd += ["--checkpoint", stage_ckpt]

            print(f"[adaptive] TRAIN S{stage} alpha={alpha:.2f} retry={retry} params={params}\n"
                  f"  cmd: {' '.join(shlex.quote(c) for c in cmd)}")
            with open(log_path, "w") as lf:
                proc = subprocess.run(cmd, cwd=sim_dir, stdout=lf, stderr=subprocess.STDOUT)
            if proc.returncode not in (0, None):
                print(f"[adaptive] WARN train exit {proc.returncode} (log {log_path})")

            run_dir = _latest_run(log_root, name)
            best    = _best_ckpt(run_dir)
            if not best:
                print(f"[adaptive] WARN no ckpt in {run_dir}")
                retry += 1; crash_scale -= args.crash_bump
                continue

            result = _eval_run(sim_dir, stage, best, None, args.eval_ep, args.job_id)
            d  = result.get("downed",  0.0)
            br = result.get("breach",  1.0)
            cr = result.get("crashes", 0.0)

            if 1 <= stage <= 3:
                passed = (d >= 0.95 * base_d and br <= base_br + 0.02 and cr <= base_cr + 0.1)
            else:
                passed = (d >= base_d)

            print(f"[adaptive] GATE S{stage} alpha={alpha:.2f} retry={retry}: "
                  f"policy={d:.3f}(breach={br:.3f},crash={cr:.3f}) "
                  f"vs scripted={base_d:.3f}(breach={base_br:.3f},crash={base_cr:.3f}) pass={passed}")
            _tsv_append(tsv, dict(stage=stage, alpha=round(alpha,4), downed=round(d,4),
                                   breach=round(br,4), crashes=round(cr,4), pass_=int(passed),
                                   crash_scale=round(crash_scale,2), job=args.job_id,
                                   ts=int(time.time())))

            if passed and alpha >= 1.0 - 1e-6:
                ckpt = best; stage_pass = True; break

            if passed:
                stage_ckpt = best
                alpha = min(1.0, alpha + args.alpha_step)
                print(f"[adaptive] partial pass -> step alpha up to {alpha:.2f}")
            else:
                crash_scale -= args.crash_bump
                retry += 1
                alpha = max(0.0, alpha - args.alpha_step)
                print(f"[adaptive] fail -> alpha -> {alpha:.2f}, crash_scale -> {crash_scale:.1f}")
                if best: stage_ckpt = best

        if not stage_pass:
            print(f"[adaptive] STOP S{stage} exhausted retries. last ckpt={ckpt}")
            _tsv_append(tsv, dict(stage=stage, alpha="FAILED", downed=-1, breach=-1, crashes=-1,
                                   pass_=0, crash_scale=round(crash_scale,2), job=args.job_id,
                                   ts=int(time.time())))
            sys.exit(42)
        print(f"[adaptive] PASS S{stage} -> ckpt={ckpt}")

    print("[adaptive] ALL DONE")

if __name__ == "__main__":
    main()
